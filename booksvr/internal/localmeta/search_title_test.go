package localmeta

import "testing"

func TestSearchTitle(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"我的北洋军旅生涯(历陈直系奉系军阀混战的幕后真相)(上层将领，生平传奇 亲身经历，一手史料)", "我的北洋军旅生涯"},
		{"《我的北洋军旅生涯》（历陈直系奉系军阀混战的幕后真相）【上层将领，生平传奇 亲身经历，一手史料】.epub", "我的北洋军旅生涯"},
		{"\ufeff《三体》【EPUB+MOBI】.epub", "三体"},
		{"《星海之旅》（校对版全本）作者：作者甲.txt", "星海之旅"},
		{"【电子书】我的北洋军旅生涯【微信公众号：某资源号】", "我的北洋军旅生涯"},
		{"酒神（阴阳冕）", "酒神（阴阳冕）"},
		{"三体Ⅱ：黑暗森林", "三体Ⅱ：黑暗森林"},
		{"哈利·波特（第2卷）", "哈利·波特（第2卷）"},
		{"我的北洋军旅生涯（修订版）", "我的北洋军旅生涯（修订版）"},
		{"小说（全三册）", "小说（全三册）"},
		{"国史研究（关于清代地方行政与人口发展的长期考察）", "国史研究（关于清代地方行政与人口发展的长期考察）"},
		{"书名：畅销与阅读的文化史", "书名：畅销与阅读的文化史"},
		{"推荐系统（第二版）", "推荐系统（第二版）"},
		{"阅读史（畅销书榜单的制作与商业文化研究）", "阅读史（畅销书榜单的制作与商业文化研究）"},
		{"《三体》与《基地》", "《三体》与《基地》"},
		{"书名（不完整的重磅推荐文字", "书名（不完整的重磅推荐文字"},
		{"（校对版全本）", "（校对版全本）"},
		{"书名（新版（校对版））", "书名（新版）"},
		{"我的北洋军旅生涯（校对版（电子书））", "我的北洋军旅生涯"},
		{"我的北洋军旅生涯（（（（（（电子书））））））", "我的北洋军旅生涯"},
	} {
		t.Run(tc.in, func(t *testing.T) {
			got := SearchTitle(tc.in)
			if got != tc.want {
				t.Fatalf("got %q want %q", got, tc.want)
			}
			if next := SearchTitle(got); next != got {
				t.Fatalf("not idempotent: %q => %q", got, next)
			}
		})
	}
}
